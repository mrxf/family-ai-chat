#!/usr/bin/env python3
"""Pack keyed mascot frames into WebP grid sheets + a Dart metadata file.

usage: pack.py <work_dir> <app_dir>
  reads  <work_dir>/out_<action>/frames/keyed/keyed_NNN.png (full-res RGBA, 24fps, 97 frames, first==last)
  writes <app_dir>/assets/mascot/<action>.webp and <app_dir>/lib/ui/mascot_sheets.dart
"""
import math, os, subprocess, sys, tempfile
import cv2
import numpy as np
from PIL import Image

work, app = sys.argv[1], sys.argv[2]
SRC_FPS = 24
LOOP_SRC_FRAMES = 96  # frame 96 duplicates frame 0 (first == last frame)
# action: (fps, rest-pose character width in output px)
ACTIONS = {
    "idle": (12, 220),
    "thinking": (12, 96),   # shown at ~34dp
    "welcome": (16, 220),
}
# Loops skip source frame 0: it is the pasted source art, whose shading differs from the generated
# frames even after colour matching, so it would flicker once per loop. The one-shot greeting keeps
# it, since it hands over from the static image.
SKIP_FIRST = {"idle", "thinking"}
PAD = 4
ALPHA_MIN = 8


def bbox(im):
    return im.getchannel("A").point(lambda a: 255 if a > ALPHA_MIN else 0).getbbox()


def body_mean(im):
    a = np.asarray(im).astype(np.float32)
    m = a[..., 3] > 250
    return a[..., :3][m].mean(axis=0)


def clean(im, target):
    """Fix the two artifacts the raw keyed frames have.

    1. Colour drift: Seedance pins the first/last frame to the source art, but the frames in between
       come out ~10% less red, so every loop "flashes" redder at the seam. Scale each frame's body
       colour so its mean matches the source art (target).
    2. Grey fringe: despilled magenta leaves semi-transparent edge pixels grey. Give every
       non-opaque pixel the colour of the nearby opaque body (alpha untouched, edges stay soft).
    """
    a = np.asarray(im).astype(np.float32)
    rgb, alpha = a[..., :3], a[..., 3]
    rgb = np.clip(rgb * (target / body_mean(im)), 0, 255)
    solid = (alpha > 250).astype(np.float32)
    k = (15, 15)
    num = cv2.blur(rgb * solid[..., None], k)
    den = cv2.blur(solid, k)
    for _ in range(3):  # widen the colour source for edge pixels far from the body
        missing = den < 1e-3
        if not missing.any():
            break
        num = np.where(missing[..., None], cv2.blur(num, k), num)
        den = np.where(missing, cv2.blur(den, k), den)
    fill = num / np.maximum(den, 1e-6)[..., None]
    edge = (alpha < 250)[..., None]
    rgb = np.where(edge, fill, rgb)
    return Image.fromarray(np.dstack([rgb, alpha]).round().astype(np.uint8))


os.makedirs(f"{app}/assets/mascot", exist_ok=True)
# Every clip starts on the source art; match all frames to its colour.
TARGET = body_mean(Image.open(f"{work}/out_idle/frames/keyed/keyed_000.png").convert("RGBA"))
entries = []
for name, (fps, rest_w) in ACTIONS.items():
    d = f"{work}/out_{name}/frames/keyed"
    n = round(LOOP_SRC_FRAMES * fps / SRC_FPS)
    off = 1 if name in SKIP_FIRST else 0
    idx = [off + round(i * SRC_FPS / fps) for i in range(n)]
    frames = [clean(Image.open(f"{d}/keyed_{i:03d}.png").convert("RGBA"), TARGET) for i in idx]
    rest = bbox(Image.open(f"{d}/keyed_000.png").convert("RGBA"))
    boxes = [bbox(f) for f in frames]
    W, H = frames[0].size
    l = max(0, min(b[0] for b in boxes) - PAD); t = max(0, min(b[1] for b in boxes) - PAD)
    r = min(W, max(b[2] for b in boxes) + PAD); btm = min(H, max(b[3] for b in boxes) + PAD)
    s = rest_w / (rest[2] - rest[0])
    fw, fh = round((r - l) * s), round((btm - t) * s)
    cols = math.ceil(math.sqrt(n))
    rows = math.ceil(n / cols)
    sheet = Image.new("RGBA", (cols * fw, rows * fh), (0, 0, 0, 0))
    for k, f in enumerate(frames):
        # resize premultiplied to avoid dark/colored halos
        c = f.crop((l, t, r, btm)).convert("RGBa").resize((fw, fh), Image.LANCZOS).convert("RGBA")
        sheet.paste(c, ((k % cols) * fw, (k // cols) * fh))
    with tempfile.TemporaryDirectory() as tmp:
        png = f"{tmp}/{name}.png"
        sheet.save(png)
        out = f"{app}/assets/mascot/{name}.webp"
        subprocess.run(["cwebp", "-quiet", "-q", "88", "-alpha_q", "100", "-exact", png, "-o", out], check=True)
    rl, rt = (rest[0] - l) * s, (rest[1] - t) * s
    rr, rb = (rest[2] - l) * s, (rest[3] - t) * s
    entries.append((name, fps, n, cols, fw, fh, (rl, rt, rr, rb)))
    print(f"{name}: {n} frames @{fps}fps, frame {fw}x{fh}, grid {cols}x{rows} = {cols*fw}x{rows*fh}, "
          f"{os.path.getsize(out)//1024} KB, decoded {cols*fw*rows*fh*4/1e6:.1f} MB")

lines = [
    "// GENERATED by the mascot animation packer — do not edit by hand.",
    "// Source: Seedance image-to-video clips keyed into transparent frames.",
    "import 'dart:ui';",
    "",
    "import 'mascot_anim.dart' show MascotMotion;",
    "",
    "class MascotSheet {",
    "  const MascotSheet({required this.asset, required this.fps, required this.frames, required this.cols,",
    "      required this.frameW, required this.frameH, required this.rest});",
    "  final String asset;",
    "  final int fps, frames, cols;",
    "  final double frameW, frameH;",
    "  /// Character bounding box in the first (rest) frame, in frame pixels.",
    "  final Rect rest;",
    "  Duration get duration => Duration(microseconds: frames * 1000000 ~/ fps);",
    "}",
    "",
    "const mascotSheets = <MascotMotion, MascotSheet>{",
]
for name, fps, n, cols, fw, fh, (rl, rt, rr, rb) in entries:
    lines.append(f"  MascotMotion.{name}: MascotSheet(asset: 'assets/mascot/{name}.webp', fps: {fps}, frames: {n}, cols: {cols}, "
                 f"frameW: {fw}, frameH: {fh}, rest: Rect.fromLTRB({rl:.1f}, {rt:.1f}, {rr:.1f}, {rb:.1f})),")
lines.append("};")
open(f"{app}/lib/ui/mascot_sheets.dart", "w").write("\n".join(lines) + "\n")
